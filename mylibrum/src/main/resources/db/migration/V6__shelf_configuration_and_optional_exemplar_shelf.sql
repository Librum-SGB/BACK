CREATE TABLE estante_prateleiras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estante_id BIGINT NOT NULL REFERENCES estantes(id),
    nome VARCHAR(150) NOT NULL,
    position_min INTEGER NOT NULL,
    position_max INTEGER NOT NULL,
    ordem INTEGER NOT NULL
);

INSERT INTO estante_prateleiras (estante_id, nome, position_min, position_max, ordem)
SELECT e.id,
       'Prateleira ' || seq.numero,
       1,
       CASE WHEN e.capacidade IS NULL OR e.capacidade <= 0 THEN 100 ELSE e.capacidade END,
       seq.numero
FROM estantes e
CROSS JOIN LATERAL generate_series(1, GREATEST(COALESCE(e.qtd_prateleiras, 0), 0)) AS seq(numero);

